FREE = 0x808080
FMAP = CORE   # совместимость со старыми скриптами
def faction_of_k(v):
    if v == FREE: return 'free'
    t = ((v >> 16) & 255, (v >> 8) & 255, v & 255)
    return CORE.get(t) or ('x_%06x' % v)
def faction_of(col, lon=None, lat=None):
    return faction_of_k((col[0] << 16) | (col[1] << 8) | col[2])

