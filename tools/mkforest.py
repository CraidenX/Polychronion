# Леса: карта лесов по исторической географии XIII века (зоны с плотностью) + неровные края (шум),
# предгорья гуще, гребни хребтов — без леса, пустыни и степи — без леса.
# Выход: umap/forest.npy — 0/1 маска леса (полная карта), umap/conifer.npy — где хвойные (у гор).
import json, os, glob
import numpy as np
from PIL import Image
import scipy.ndimage as nd
SP = os.path.dirname(os.path.abspath(__file__)) + '/'
fit = json.load(open(SP + 'umap/fit.json'))
P = np.asarray(Image.open(sorted(glob.glob(SP + '../source/*political*.png'))[0]).convert('RGB')).astype(np.int32)
kP = (P[..., 0] << 16) | (P[..., 1] << 8) | P[..., 2]
G = np.asarray(Image.open(sorted(glob.glob(SP + '../source/*regions*.png'))[0]).convert('RGB')).astype(np.int32)
kG = (G[..., 0] << 16) | (G[..., 1] << 8) | G[..., 2]
H, W = kP.shape
k = W / fit.get('W', 2000); l0, sx, p0, sy = fit['p'][0], fit['p'][1] * k, fit['p'][2], fit['p'][3] * k
# (долгота, широта, полуось по долготе, по широте, плотность, подпись)
ZONES = [
 (19.0, 44.3, 3.0, 1.3, 0.75, 'Шумадия, Сербия, Босния'), (17.6, 45.0, 2.0, 0.7, 0.7, 'славонские дубравы'),
 (15.8, 45.3, 1.3, 0.6, 0.6, 'Хорватия'), (23.5, 42.7, 2.6, 0.65, 0.55, 'Стара-Планина, Средна-Гора'),
 (24.4, 41.7, 1.4, 0.5, 0.65, 'Родопы'), (21.5, 41.7, 1.3, 0.7, 0.45, 'горы Македонии'),
 (21.0, 39.8, 1.0, 1.0, 0.45, 'Пинд, Эпир'), (22.2, 37.6, 0.8, 0.5, 0.3, 'Аркадия'),
 (26.0, 44.6, 0.75, 0.35, 0.85, 'Кодрии Влэсией'), (25.0, 44.1, 0.8, 0.3, 0.75, 'Телеорман'),
 (25.0, 45.3, 3.2, 0.4, 0.65, 'предгорья Карпат'), (27.0, 43.7, 0.75, 0.35, 0.6, 'Делиорман'),
 (27.7, 42.0, 0.6, 0.35, 0.75, 'Странджа'), (29.8, 40.6, 1.6, 0.4, 0.5, 'Вифиния'),
 (33.0, 41.3, 3.6, 0.45, 0.75, 'Пафлагония'), (38.5, 40.8, 3.2, 0.4, 0.7, 'Понтийские Альпы'),
 (42.0, 42.2, 1.5, 0.7, 0.85, 'Колхида'), (45.2, 41.9, 1.2, 0.5, 0.55, 'Кахетия'),
 (44.0, 43.3, 3.0, 0.5, 0.55, 'Северный Кавказ'), (39.5, 44.4, 1.0, 0.5, 0.6, 'Кубань'),
 (34.2, 44.65, 0.6, 0.16, 0.65, 'Крымские горы'), (49.2, 37.5, 1.6, 0.9, 0.85, 'Гирканские леса'),
 (46.5, 39.3, 0.8, 0.5, 0.4, 'Арцах'), (31.3, 37.2, 2.6, 0.5, 0.35, 'Западный Тавр'),
 (35.0, 37.2, 1.0, 0.4, 0.35, 'Киликийский Тавр'), (36.3, 36.6, 0.4, 0.6, 0.4, 'Аман'),
 (35.9, 34.1, 0.25, 0.4, 0.35, 'ливанские кедры'), (32.9, 34.95, 0.28, 0.13, 0.55, 'Троодос'),
 (16.3, 39.2, 0.6, 0.6, 0.7, 'Сила'), (15.5, 40.6, 1.2, 0.8, 0.45, 'Апеннины'), (14.2, 41.9, 1.0, 0.7, 0.4, 'Абруцци'),
 (14.6, 37.9, 0.5, 0.25, 0.45, 'Неброди'), (28.2, 39.3, 1.3, 0.6, 0.35, 'горы Мисии'), (26.9, 39.75, 0.4, 0.3, 0.5, 'Ида'),
 (23.7, 38.6, 0.6, 0.35, 0.35, 'Эвбея'), (20.0, 42.5, 1.2, 0.6, 0.5, 'Зета, Арбанон'),
]
yy, xx = np.mgrid[0:H, 0:W]
lon = l0 + xx / sx; lat = p0 - yy / sy
D = np.zeros((H, W), np.float32)
for lo, la, rx, ry, dens, _ in ZONES:
    q = ((lon - lo) / rx) ** 2 + ((lat - la) / ry) ** 2
    D = np.maximum(D, (dens * np.exp(-q ** 2)).astype(np.float32))
del yy, xx, lon, lat
sea = np.isin(kP, [0x001F48, 0x000020])
ridge = np.isin(kG, [0x8B5A2B, 0x4A2F1A, 0xFF00FF, 0x5E5E5E]) | (kP == 0x5E5E5E)
dr = nd.distance_transform_edt(~ridge)
D += np.where((dr > 3) & (dr < 30), 0.22, 0) * (D > 0.12)          # предгорья гуще
rng = np.random.default_rng(1203)
def noise(scale):
    n = rng.random((H // scale + 2, W // scale + 2)).astype(np.float32)
    return np.asarray(Image.fromarray((n * 255).astype(np.uint8)).resize((W + 2 * scale, H + 2 * scale), Image.BICUBIC), np.float32)[scale:scale + H, scale:scale + W] / 255 - 0.5
nz = noise(40) * 0.6 + noise(14) * 0.3 + noise(5) * 0.12
forest = (D + nz * 0.7 > 0.55) & ~sea & (dr > 2.5)
forest = nd.binary_opening(forest, iterations=1)
conifer = dr < 26
np.save(SP + 'umap/forest.npy', forest); np.save(SP + 'umap/conifer.npy', conifer & forest)
print('лес, % суши:', round(forest.sum() / (~sea).sum() * 100, 1))
